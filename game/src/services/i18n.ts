/** All string keys (used by tests to verify every language is complete). */
export const STR_KEYS = Object.keys(en) as StrKey[];

export function isLang(x: unknown): x is Lang {
  return typeof x === 'string' && (LANGS as readonly string[]).includes(x);
}

let current: Lang = 'en';

export function detectLang(): Lang {
  const langs = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : [];
  for (const l of langs) {
    const code = (l || '').toLowerCase().slice(0, 2);
    if (isLang(code)) return code;
  }
  return 'en';
}

export function setLang(lang: Lang): void {
  current = lang;
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export function getLang(): Lang {
  return current;
}

export function t(key: StrKey, vars?: Record<string, string | number>): string {
  let s = DICTS[current][key] ?? en[key];
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}
